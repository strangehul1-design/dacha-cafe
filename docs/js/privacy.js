// Страница политики: если в админке задан собственный юридический текст — показываем его,
// иначе — краткий типовой текст о том, какие данные собирает сайт.
const root = document.getElementById('root');

const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

try {
  const r = await fetch('/dacha-cafe/data/privacy.json').then((x) => x.json());
  const c = r.contacts;
  const body = r.text
    ? `<div class="legal">${esc(r.text)}</div>`
    : `<p>Эта страница объясняет, какие данные мы получаем, когда вы заказываете еду или бронируете столик на сайте кафе «${esc(r.brand.full || r.brand.name)}», и как мы ими пользуемся.</p>
       <h2>Какие данные мы собираем</h2>
       <ul>
         <li>имя и номер телефона — чтобы подтвердить заказ или бронь и связаться с вами;</li>
         <li>адрес доставки — чтобы курьер мог вас найти;</li>
         <li>содержимое заказа, выбранный способ оплаты и ваши комментарии.</li>
       </ul>
       <h2>Зачем мы их используем</h2>
       <p>Только для выполнения вашего заказа или брони. Мы не продаём данные и не используем их для рекламы третьих лиц.</p>
       <h2>Как долго храним</h2>
       <p>Пока это нужно для выполнения заказа и учёта работы кафе. Вы можете попросить удалить ваши данные — позвоните нам или напишите.</p>
       <h2>Как с нами связаться</h2>
       <p>${esc(c.address)}${c.place ? ', ' + esc(c.place) : ''}.<br />Телефон: ${esc(c.phone)}${c.email ? '<br />Почта: ' + esc(c.email) : ''}</p>`;
  root.innerHTML = `<a class="back" href="/dacha-cafe/">← На главную</a><h1>Политика конфиденциальности</h1>${body}`;
} catch {
  root.querySelector('p').textContent = 'Не удалось загрузить страницу. Попробуйте обновить её.';
}

const pad = (n) => String(n).padStart(3, '0');

export function buildSeedMenu() {
  const categories = seedCategories.map((c, i) => ({
    id: c.id,
    name: c.name,
    note: c.note || '',
    order: i,
    hidden: false,
    from: '',
    to: '',
  }));

  const counters = {};
  const dishes = rows.map(([cat, name, desc, price, weight, img, extra = {}], i) => {
    counters[cat] = (counters[cat] || 0) + 1;
    const needsPrice = price == null;
    return {
      id: 'd' + pad(i + 1),
      categoryId: cat,
      name,
      desc,
      price: needsPrice ? 0 : price,
      weight,
      image: img ? IMG + img : '',
      tags: extra.tags || [],
      options: extra.options || [],
      order: counters[cat],
      stop: false,
      hidden: needsPrice,
      needsPrice,
      hit: false,
      forTable: true,
      forDelivery: true,
    };
  });

  const halls = [
    { id: 'big', name: 'Большой зал', seats: 85 },
    { id: 'mid', name: 'Средний зал', seats: 45 },
    { id: 'small1', name: 'Малый зал 1', seats: 25 },
    { id: 'small2', name: 'Малый зал 2', seats: 25 },
  ];

  const layout = [
    ['big', 1, 6],
    ['mid', 7, 10],
    ['small1', 11, 12],
    ['small2', 13, 14],
  ];
  const tables = [];
  for (const [hall, from, to] of layout) {
    for (let n = from; n <= to; n++) tables.push({ id: 't' + n, number: String(n), hallId: hall, code: randomCode(), menuId: 'main' });
  }

  const menus = [
    { id: 'main', name: 'Основное меню', categoryIds: null },
    { id: 'kids', name: 'Детское меню', categoryIds: ['kids', 'desert', 'sauces', 'drinks'] },
  ];

  return { categories, dishes, halls, tables, menus };
}

